/* Gear outline (decal), centered on 0,0 */
function gear(r, teeth, cls) {
  let d = '';
  for (let i = 0; i < teeth * 2; i++) {
    const a0 = (i / (teeth * 2)) * Math.PI * 2, a1 = ((i + 1) / (teeth * 2)) * Math.PI * 2;
    const rr = i % 2 ? r : r * 1.25;
    d += (i ? 'L' : 'M') + n(Math.cos(a0) * rr) + ' ' + n(Math.sin(a0) * rr) + 'L' + n(Math.cos(a1) * rr) + ' ' + n(Math.sin(a1) * rr);
  }
  return `<path class="${cls}" d="${d}Z"/><circle class="wall-t" r="${n(r * 0.42)}"/>`;
}
/* Ship's wheel (decal) */
function wheel(r, cls) {
  let d = '';
  for (let i = 0; i < 8; i++) { const a = (i / 8) * Math.PI * 2; d += `M${n(Math.cos(a) * r * 0.3)} ${n(Math.sin(a) * r * 0.3)}L${n(Math.cos(a) * r * 1.3)} ${n(Math.sin(a) * r * 1.3)}`; }
  return `<path class="ln thick" d="${d}"/><circle class="${cls}" r="${n(r)}" style="fill:none;stroke-width:3"/><circle class="${cls}" r="${n(r)}" style="fill:none"/><circle class="${cls}" r="${n(r * 0.32)}"/>`;
}

