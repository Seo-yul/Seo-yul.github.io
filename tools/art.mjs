  textL(Y, x, z, str, size, cls = 'sign') { const [sx, sy] = this.P(x, Y, z); return this.add(`<text class="${cls}" font-size="${size}" transform="matrix(${n(COS)} 0.5 0 1 ${n(sx)} ${n(sy)})">${str}</text>`); }
  textR(X, y, z, str, size, cls = 'sign') { const [sx, sy] = this.P(X, y, z); return this.add(`<text class="${cls}" font-size="${size}" transform="matrix(${n(COS)} -0.5 0 1 ${n(sx)} ${n(sy)})">${str}</text>`); }
  /* Any 2D markup laid onto the left or right face, local origin at (x|y, z), local y pointing down */
  decalL(Y, x, z, markup) { const [sx, sy] = this.P(x, Y, z); return this.add(`<g transform="matrix(${n(COS)} 0.5 0 1 ${n(sx)} ${n(sy)})">${markup}</g>`); }
  decalR(X, y, z, markup) { const [sx, sy] = this.P(X, y, z); return this.add(`<g transform="matrix(${n(COS)} -0.5 0 1 ${n(sx)} ${n(sy)})">${markup}</g>`); }
  /* Raised lot every scene stands on */
  lot(w, d, m = 'pave') { this.lotWD = [w, d]; return this.box(0, 0, -8, w, d, 8, m); }
